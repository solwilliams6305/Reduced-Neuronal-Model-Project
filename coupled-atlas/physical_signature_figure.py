a=ax[0]
a.axhspan(-1.3,0,color="#e9f5f0",zorder=0); a.axhline(0,color="grey",lw=1,ls="--")
a.plot(-g,exk8,"o-",color="#264653",label=r"$\epsilon=0.008$")
a.plot(-g,exk15,"s-",color="#e76f51",label=r"$\epsilon=0.015$")
